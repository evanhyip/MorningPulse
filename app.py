# app.py
import pandas as pd
import plotly.express as px
import streamlit as st

from core.brief_generator import generate_executive_brief, query_cortex_chat
from core.detector import detect_today_anomalies, fetch_telemetry_from_snowflake

st.set_page_config(page_title="MorningPulse", page_icon="☀️", layout="wide")

# --- EXECUTIVE DISPLAY CONFIGURATION ---
METRIC_DISPLAY_CONFIG = {
    "checkout_failure_rate_pct": {
        "title": "Payment Checkout Failure Rate",
        "unit_override": "%",
        "description": "Percentage of checkout transactions failing at payment gateway.",
    },
    "refund_request_surge_count": {
        "title": "Daily Refund Requests",
        "unit_override": "requests",
        "description": "Volume of customer chargebacks and refund inquiries.",
    },
    "api_latency_p99_ms": {
        "title": "Platform Response Latency (P99)",
        "unit_override": "ms",
        "description": "Latency for the slowest 1% of backend API requests.",
    },
    "daily_active_users": {
        "title": "Daily Active Users",
        "unit_override": "users",
        "description": "Total unique user sessions recorded across the platform.",
    },
    "cart_abandonment_rate_pct": {
        "title": "Cart Abandonment Rate",
        "unit_override": "%",
        "description": "Percentage of sessions where users dropped before finalizing purchase.",
    },
}


def get_severity_badge(z_score: float) -> str:
    abs_z = abs(z_score)
    if abs_z >= 3.0:
        return "🔴 Critical Outlier"
    elif abs_z >= 2.0:
        return "🟠 Moderate Warning"
    return "🟢 Within Normal Limits"


# --- SIDEBAR: SYSTEM & CORTEX CONFIGURATION ---
with st.sidebar:
    st.header("⚙️ Snowflake Cortex Settings")
    selected_model = st.selectbox(
        "AI Model",
        options=[
            "llama3.1-8b",
            "llama3.1-70b",
            "llama3.1-405b",
            "mistral-large2",
            "mixtral-8x7b",
            "snowflake-arctic",
        ],
        index=0,
        help="Select foundational LLM hosted natively in Snowflake Cortex.",
    )
    max_tokens = st.slider(
        "Max Output Tokens",
        min_value=128,
        max_value=2048,
        value=512,
        step=64,
        help="Hard cap on token length generated by AI_COMPLETE.",
    )
    temperature = st.slider(
        "Temperature",
        min_value=0.0,
        max_value=1.0,
        value=0.2,
        step=0.05,
        help="Lower values yield deterministic, grounded operational briefs.",
    )
    st.divider()
    st.caption("Warehouse: `COMPUTE_WH`")
    st.caption("Database: `MORNINGPULSE_DB.TELEMETRY`")


# --- DATA RETRIEVAL (CACHED) ---
@st.cache_data(ttl=600)
def load_telemetry_data() -> pd.DataFrame:
    return fetch_telemetry_from_snowflake()


st.title("☀️ MorningPulse")
st.caption("Executive Telemetry Intelligence · Powered by Snowflake Cortex")

with st.spinner("Connecting to Snowflake warehouse..."):
    try:
        df = load_telemetry_data()
    except Exception as e:
        st.error(f"Failed to query Snowflake: {e}")
        st.stop()

anomalies = detect_today_anomalies(df)

# --- INCIDENT OVERVIEW (EXECUTIVE-FRIENDLY) ---
st.markdown("### 🚨 Critical Issues Requiring Attention")
if anomalies:
    cols = st.columns(min(len(anomalies), 4))
    for idx, a in enumerate(anomalies):
        metric_key = a["metric_name"]
        cfg = METRIC_DISPLAY_CONFIG.get(
            metric_key,
            {
                "title": metric_key.replace("_", " ").title(),
                "unit_override": a["unit"],
            },
        )
        severity = get_severity_badge(a["z_score"])
        unit = cfg.get("unit_override", a["unit"])

        with cols[idx % 4]:
            st.metric(
                label=f"{a['department'].upper()} · {cfg['title']}",
                value=f"{a['current_value']} {unit}",
                delta=f"{a['percent_delta']} vs. 14-day normal",
                delta_color="inverse",
            )
            baseline_val = a["expected_baseline"]
            baseline_str = f"{baseline_val} {unit}" if baseline_val is not None else "N/A"
            st.caption(f"**Status:** {severity}\n\n*Historical Normal:* ~{baseline_str}")
else:
    st.success("All business and operational metrics are operating within normal 14-day parameters.")

# --- HISTORICAL PERFORMANCE TREND ---
st.markdown("### 📈 Historical Performance Trend")

# Map raw database metric names to readable executive titles
metric_options = {
    METRIC_DISPLAY_CONFIG.get(k, {}).get("title", k.replace("_", " ").title()): k
    for k in df["metric_name"].unique()
}

selected_label = st.selectbox(
    "Select metric to inspect:",
    options=list(metric_options.keys()),
    index=0,
)
selected_metric_key = metric_options[selected_label]

metric_df = (
    df[df["metric_name"] == selected_metric_key]
    .sort_values("metric_date")
    .tail(14)
)

fig = px.line(
    metric_df,
    x="metric_date",
    y="metric_value",
    markers=True,
    title=f"14-Day Trajectory: {selected_label}",
    labels={"metric_date": "Date", "metric_value": "Observed Value"},
)
st.plotly_chart(fig, use_container_width=True)

# --- EXECUTIVE INCIDENT BRIEFING ---
st.divider()
st.subheader("📋 Executive Incident Briefing")

if st.button("Generate Morning Brief", type="primary"):
    with st.spinner(f"Snowflake Cortex ({selected_model}) is synthesizing telemetry..."):
        try:
            brief = generate_executive_brief(
                anomalies=anomalies,
                model=selected_model,
                max_tokens=max_tokens,
                temperature=temperature,
            )
            st.session_state["brief"] = brief
        except Exception as e:
            st.error(f"Error calling Snowflake Cortex: {e}")

if "brief" in st.session_state and st.session_state["brief"]:
    with st.container(border=True):
        st.markdown(st.session_state["brief"])

    st.markdown("#### ⚡ Staged Remediation Actions")
    col_act1, col_act2 = st.columns(2)
    with col_act1:
        if st.button("🚨 Trigger Rollback (`checkout-service-v2.14`)"):
            st.success("Rollback command dispatched to cluster via Kubernetes API.")
    with col_act2:
        if st.button("📢 Broadcast Status Incident Advisory"):
            st.info("Incident advisory published to company status channels.")

# --- CONVERSATIONAL CORTEX AGENT (GATED BEHIND BRIEF GENERATION) ---
st.divider()
st.subheader("💬 Ask the AI Chief of Staff")
st.caption("Drill down into incident causality, customer impact, or staged remediation.")

if not st.session_state.get("brief"):
    st.info(
        "🔒 **Agent Locked:** Click **Generate Morning Brief** above to synthesize telemetry before starting an investigation."
    )
else:
    if "chat_history" not in st.session_state:
        st.session_state["chat_history"] = []

    # Render ongoing chat transcript
    for msg in st.session_state["chat_history"]:
        with st.chat_message(msg["role"]):
            st.markdown(msg["content"])

    # Chat prompt submission
    if prompt := st.chat_input("Ask about root causes, rollback steps, or financial exposure..."):
        st.session_state["chat_history"].append({"role": "user", "content": prompt})
        with st.chat_message("user"):
            st.markdown(prompt)

        with st.chat_message("assistant"):
            with st.spinner(f"Consulting Snowflake Cortex ({selected_model})..."):
                try:
                    agent_response = query_cortex_chat(
                        conversation_history=st.session_state["chat_history"],
                        anomalies=anomalies,
                        system_brief=st.session_state["brief"],
                        model=selected_model,
                        max_tokens=max_tokens,
                        temperature=temperature,
                    )
                    st.markdown(agent_response)
                    st.session_state["chat_history"].append(
                        {"role": "assistant", "content": agent_response}
                    )
                except Exception as e:
                    st.error(f"Error querying Snowflake Cortex Agent: {e}")